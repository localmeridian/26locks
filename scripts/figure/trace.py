#!/usr/bin/env python3
"""Turn render.py's PNGs into the site's figure assets (needs ImageMagick and potrace).

For each view writes to site/public/figure/:
  <view>.svg        <g id="fill"> body silhouette, <g id="lines"> contour lines;
                    both inherit fill from the page, so they follow the theme
  <view>-shade.webp grayscale luminance mask: white where the form turns away from the light
Run: python3 trace.py [view ...]
"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
DEST = os.path.normpath(os.path.join(HERE, "..", "..", "public", "figure"))
# render size -> viewBox size, per view
SIZES = {
    "front": ((1600, 4000), (400, 1000)), "back": ((1600, 4000), (400, 1000)),
    "medial": ((1560, 900), (260, 150)), "lateral": ((1560, 900), (260, 150)), "sole": ((720, 1560), (120, 260)),
    "hand": ((1800, 2350), (360, 470)),
}
FINGERS = ["thumb", "index", "middle", "ring", "little"]

def sh(*a): subprocess.run(a, check=True)

def potrace(png_args, turd, alpha, opt):
    """Trace a black-on-white bitmap; return potrace's path data and its transform."""
    with tempfile.TemporaryDirectory() as t:
        pbm, svg = os.path.join(t, "i.pbm"), os.path.join(t, "o.svg")
        sh("magick", *png_args, pbm)
        sh("potrace", pbm, "-s", "--flat", "-t", str(turd), "-a", str(alpha), "-O", str(opt), "-o", svg)
        s = open(svg).read()
    return " ".join(re.findall(r'<path d="([^"]+)"', s)).replace("\n", " ")

def view(v):
    (rw, rh), (w, h) = SIZES[v]
    k = w / rw
    tf = f"translate(0 {h}) scale({k / 10:g} {-k / 10:g})"
    shade, line = os.path.join(OUT, f"{v}-shade.png"), os.path.join(OUT, f"{v}-line.png")
    fill = potrace([shade, "-alpha", "extract", "-threshold", "50%", "-negate"], 50, 1.3, 2)
    lines = potrace([line, "-alpha", "remove", "-colorspace", "gray", "-threshold", "60%"], 6, 1.2, 1)
    os.makedirs(DEST, exist_ok=True)
    with open(os.path.join(DEST, f"{v}.svg"), "w") as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">\n'
                f'<!-- Rendered from the MakeHuman base mesh (CC0) with MPFB2 in Blender; see scripts/figure. -->\n'
                f'<g id="fill"><path transform="{tf}" d="{fill}"/></g>\n'
                f'<g id="lines"><path transform="{tf}" d="{lines}"/></g>\n</svg>\n')
    # ink = how far each pixel falls below the lit tone; zero outside the body
    sh("magick", shade, "(", "+clone", "-alpha", "extract", ")",
       "(", "-clone", "0", "-background", "white", "-alpha", "remove", "-colorspace", "gray", "-negate", "-level", "28%,72%", ")",
       "-delete", "0", "-compose", "multiply", "-composite", "-resize", "50%", "-quality", "82",
       os.path.join(DEST, f"{v}-shade.webp"))
    print(v, os.path.getsize(os.path.join(DEST, f"{v}.svg")), os.path.getsize(os.path.join(DEST, f"{v}-shade.webp")))

def hand_data():
    """src/lib/hand-art.ts: one smoothed outline per finger, and label and palm points."""
    import json
    (rw, rh), (w, h) = SIZES["hand"]
    k = w / rw
    tf = f"translate(0 {h}) scale({k / 10:g} {-k / 10:g})"
    lm = json.load(open(os.path.join(OUT, "hand.json")))
    fingers = {}
    for f in FINGERS:
        d = potrace([os.path.join(OUT, f"hand-{f}.png"), "-alpha", "extract", "-blur", "0x10", "-threshold", "50%", "-negate"], 200, 1.3, 2)
        fingers[f] = {"d": d, "label": lm[f]["mid"], "tip": lm[f]["tip"], "base": lm[f]["base"]}
    src = os.path.normpath(os.path.join(HERE, "..", "..", "src", "lib", "hand-art.ts"))
    with open(src, "w") as o:
        o.write("// Generated by scripts/figure/trace.py from the rendered left hand (palm toward the viewer,\n"
                "// fingers up; viewBox 360×470). Each finger outline is for tinting and hit areas;\n"
                "// the drawing itself is public/figure/hand.svg. Do not edit by hand.\n")
        o.write(f"export const HAND_W = {w};\nexport const HAND_H = {h};\n")
        o.write(f"export const fingerTransform = '{tf}';\n")
        o.write(f"export const palmCentre: [number, number] = {json.dumps(lm['palm'])};\n")
        o.write("export const fingersArt: Record<string, { d: string; label: [number, number]; tip: [number, number]; base: [number, number] }> = ")
        o.write(json.dumps(fingers, indent=1) + ";\n")
    print("hand-art.ts", os.path.getsize(src))

if __name__ == "__main__":
    for v in sys.argv[1:] or list(SIZES):
        view(v)
        if v == "hand": hand_data()
