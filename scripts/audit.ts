// Provenance audit. Checks that every claim on the site traces to a source and
// flags what needs a human look. Writes research/audits/<date>.md.
//   npm run audit          structural checks
//   npm run audit:links    also fetches every source URL (slow; needs network)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { selData } from '../src/data/sels.ts';
import { depths, sixthDepth, DATASET_REVIEWED } from '../src/data/depths.ts';
import { positions } from '../src/data/positions.ts';

type Src = { key: string; title: string; url?: string; grade: 'high' | 'medium' | 'low'; reliability?: string; accessed?: string };
const sources: Src[] = JSON.parse(readFileSync(new URL('../src/data/sources.json', import.meta.url), 'utf8'));
const byKey = new Map(sources.map((s) => [s.key, s]));
const today = new Date().toISOString().slice(0, 10);
const STALE_DAYS = 365;
const checkLinks = process.argv.includes('--links');

const errors: string[] = [];
const warnings: string[] = [];
const review: string[] = [];
const cited = new Set<string>();

function checkKeys(where: string, keys: string[]) {
  for (const k of keys) {
    cited.add(k);
    if (!byKey.has(k)) errors.push(`${where}: cites unknown source **${k}**`);
  }
}
const ageDays = (d: string) => (Date.parse(today) - Date.parse(d)) / 864e5;

for (const s of selData) {
  const where = `Lock ${s.n} (${s.name})`;
  const keys = [...new Set(s.sources)];
  checkKeys(where, keys);
  s.holds.forEach((h) => checkKeys(`${where}, hold “${h.name}”`, h.sources ?? []));
  if (keys.length < 2) errors.push(`${where}: only ${keys.length} source — needs two independent sources`);
  if (!keys.some((k) => byKey.get(k)?.grade === 'high')) warnings.push(`${where}: no high-grade source`);
  if (s.confidence !== 'high') review.push(`${where}: confidence **${s.confidence}**${s.notes ? ` — ${s.notes}` : ''}`);
  if (!positions[s.n]?.length) errors.push(`${where}: no position on the map`);
  const reviewed = s.reviewed ?? DATASET_REVIEWED;
  if (ageDays(reviewed) > STALE_DAYS) warnings.push(`${where}: last reviewed ${reviewed} — due for re-check`);
}
const inDepths = depths.flatMap((d) => d.sels).sort((a, b) => a - b);
if (inDepths.join() !== Array.from({ length: 26 }, (_, i) => i + 1).join()) errors.push('Depths do not cover locks 1–26 exactly once');
for (const s of selData) {
  const d = depths.find((d) => d.sels.includes(s.n));
  if (d && d.n !== s.depth) errors.push(`Lock ${s.n}: depth ${s.depth} in sels.ts but listed under ${d.name}`);
}
for (const d of depths) {
  checkKeys(d.name, d.sources);
  if (d.elementConfidence !== 'high') review.push(`${d.name}: element “${d.element}” is ${d.elementConfidence} confidence`);
  if (ageDays(d.reviewed) > STALE_DAYS) warnings.push(`${d.name}: last reviewed ${d.reviewed} — due for re-check`);
}
checkKeys('6th Depth', sixthDepth.sources);


for (const s of sources) {
  if (!s.url) warnings.push(`Source ${s.key} (“${s.title}”) has no URL — print source; check against a physical copy`);
  if (s.accessed && ageDays(s.accessed) > STALE_DAYS) warnings.push(`Source ${s.key} last accessed ${s.accessed}`);
}

const linkRows: string[] = [];
if (checkLinks) {
  const targets = sources.filter((s) => s.url);
  await Promise.all(targets.map(async (s) => {
    let status = 'error';
    try {
      const r = await fetch(s.url!, { method: 'GET', redirect: 'follow', signal: AbortSignal.timeout(15000), headers: { 'user-agent': 'Mozilla/5.0 (26locks audit)' } });
      status = String(r.status);
    } catch (e) { status = (e as Error).name; }
    if (status !== '200') linkRows.push(`| ${s.key} | ${status} | ${s.url} |`);
  }));
  linkRows.sort();
}

const uncited = sources.filter((s) => !cited.has(s.key)).map((s) => s.key);
const list = (xs: string[]) => (xs.length ? xs.map((x) => `- ${x}`).join('\n') : '_None._');
const report = `# Provenance audit — ${today}

Generated by \`npm run audit${checkLinks ? ':links' : ''}\` (site/scripts/audit.ts). Data set reviewed: ${DATASET_REVIEWED}.

| | |
|---|---|
| Locks | ${selData.length} |
| Sources | ${sources.length} (${['high', 'medium', 'low'].map((g) => `${sources.filter((s) => s.grade === g).length} ${g}`).join(', ')}) |
| Sources cited by site data | ${cited.size} |
| Errors | ${errors.length} |
| Warnings | ${warnings.length} |

## Errors (must fix)
${list(errors)}

## Needs human review (lower-confidence claims)
${list(review)}

## Warnings
${list(warnings)}

## Sources not yet cited by site data
History, glossary and flow pages cite these through page text; check they are still wanted.

${uncited.join(', ') || '_None._'}
${checkLinks ? `\n## Links that did not return 200\n\n| Key | Status | URL |\n|---|---|---|\n${linkRows.join('\n') || '| — | all OK | |'}\n` : ''}
## How to resolve
1. Open the claim's notes in \`research/notes/\` and its sources on the /sources page.
2. Fix the data in \`site/src/data/\`, record the reasoning in \`research/curation-log.md\`, and bump \`reviewed\`.
3. Re-run the audit and commit the report alongside the fix.
`;
const dir = new URL('../audits/', import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL(`${today}.md`, dir), report);
console.log(`audit: ${errors.length} errors, ${warnings.length} warnings, ${review.length} for review → audits/${today}.md`);
process.exit(errors.length ? 1 : 0);
